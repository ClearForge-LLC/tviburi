#[no_mangle]
pub unsafe extern "C" fn reset() -> ! {
    write_volatile(RCC_AHB4ENR, 0x7FF);
    #[cfg(path = "valid")]
    {
        afsel(GPIOA, 5, 5);
        mode(GPIOA, 5, 2);
    }
    #[cfg(path = "blank")]
    {
        afsel(GPIOA, 5, 6);
        mode(GPIOA, 5, 2);
    }
    #[cfg(path = "blankfirst")]
    {
        mode(GPIOA, 6, 2);
    }
    #[cfg(path = "twice")]
    {
        afsel(GPIOA, 5, 6);
        mode(GPIOA, 5, 2);
        mode(GPIOA, 6, 1);
    }
    #[cfg(path = "afterwards")]
    {
        afsel(GPIOA, 5, 5);
        mode(GPIOA, 5, 2);
        afsel(GPIOA, 5, 6);
    }
    #[cfg(path = "afrh")]
    {
        write_volatile((GPIOA + AFRH) as *mut u16, (r(GPIOA, AFRH) as u16) & !(0xF << 4));
        mode(GPIOA, 9, 2);
    }
    #[cfg(path = "package")]
    {
        mode(GPIOH, 2, 1);
    }
    #[cfg(path = "packageinput")]
    {
        let mut port = GPIOA;
        while port <= 0x5802_2800 {
            w(port, MODER, 0);
            port += 0x400;
        }
    }
    #[cfg(path = "pc2")]
    {
        mode(GPIOC, 2, 1);
    }
    #[cfg(path = "pupdr")]
    {
        w(GPIOA, PUPDR, (r(GPIOA, PUPDR) & !3) | 3);
    }
    #[cfg(path = "lckr")]
    {
        w(GPIOA, LCKR, (1 << 16) | 1);
    }
    #[cfg(path = "brr")]
    {
        w(GPIOA, 0x28, 1);
    }
    #[cfg(path = "read")]
    {
        write_volatile(MARK_READ, r(GPIOA, 0x2C));
    }
    #[cfg(path = "bsrr")]
    {
        w(GPIOA, ODR, 0);
        w(GPIOA, BSRR, (1 << 16) | 1);
        write_volatile(MARK_READ, r(GPIOA, ODR));
    }
    #[cfg(path = "bsrrhalf")]
    {
        write_volatile((GPIOA + BSRR) as *mut u16, 1);
        write_volatile(MARK_READ, r(GPIOA, ODR));
        write_volatile((GPIOA + BSRR + 2) as *mut u16, 1);
        write_volatile(MARK_READ, (read_volatile(MARK_READ) << 4) | r(GPIOA, ODR));
    }
    #[cfg(path = "otyper")]
    {
        w(GPIOA, OTYPER, 0x00C0);
        write_volatile(MARK_READ, r(GPIOA, OTYPER));
    }
    #[cfg(path = "ardupilot")]
    replay(&SEQ_AP);
    #[cfg(path = "gen-s03")]
    replay(&SEQ_S03);
    write_volatile(MARK_AFTER, 0xAF7E_0002);
    loop {}
}

#[panic_handler]
fn panic(_: &core::panic::PanicInfo) -> ! {
    loop {}
}
