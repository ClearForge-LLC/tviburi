#![no_std]
#![no_main]
#![allow(dead_code)]

use core::ptr::{read_volatile, write_volatile};

const RCC_AHB4ENR: *mut u32 = 0x5802_44E0 as *mut u32;
const GPIOA: usize = 0x5802_0000;
const GPIOB: usize = 0x5802_0400;
const GPIOD: usize = 0x5802_0C00;
const RCC_APB2ENR: *mut u32 = 0x5802_44F0 as *mut u32;
const RCC_APB1LENR: *mut u32 = 0x5802_44E8 as *mut u32;
const TIM1: usize = 0x4001_0000;
const IDR: usize = 0x10;
const GPIOC: usize = 0x5802_0800;
const GPIOH: usize = 0x5802_1C00;
const GPIOK: usize = 0x5802_2800;
const MODER: usize = 0x00;
const OTYPER: usize = 0x04;
const PUPDR: usize = 0x0C;
const ODR: usize = 0x14;
const BSRR: usize = 0x18;
const LCKR: usize = 0x1C;
const AFRL: usize = 0x20;
const AFRH: usize = 0x24;
/// Marker in DTCM, read back by the test: the firmware got past its last guarded access.
const MARK_AFTER: *mut u32 = 0x2000_0104 as *mut u32;
/// Where a read's value is kept, so the test can see it.
const MARK_READ: *mut u32 = 0x2000_0108 as *mut u32;
const MARK_READ2: *mut u32 = 0x2000_010C as *mut u32;

unsafe fn w(port: usize, off: usize, v: u32) {
    write_volatile((port + off) as *mut u32, v);
}

unsafe fn r(port: usize, off: usize) -> u32 {
    read_volatile((port + off) as *const u32)
}

unsafe fn mode(port: usize, pin: u32, m: u32) {
    w(port, MODER, (r(port, MODER) & !(3 << (2 * pin))) | (m << (2 * pin)));
}

unsafe fn afsel(port: usize, pin: u32, af: u32) {
    let off = if pin < 8 { AFRL } else { AFRH };
    let sh = 4 * (pin & 7);
    w(port, off, (r(port, off) & !(0xF << sh)) | (af << sh));
}

/// A timer's CH1 in PWM mode 1 (OC1M = 0110, RM0433 Rev 9 §38.4.7 p1599 for TIM1, §39.4.7 p1688 for TIM2-5; p1557), its
/// output enabled (CC1E, §38.4.11 p1605), ARR = 99 and CCR1 = `ccr` (0 holds the output low, more than ARR high), the
/// counter running, and its clock enabled by bit `bit` of `enr` (TIM1EN, APB2ENR bit 0; TIM2EN, TIM5EN, APB1LENR bits 0
/// and 3, p464). TIM1 also gets MOE (BDTR). A busy loop then lets virtual time pass, so the stock timer has set its
/// output before the caller goes on.
#[cfg(any(path = "afodr", path = "afenter", path = "afenterhigh", path = "afout", path = "afentern", path = "afswitch"))]
unsafe fn tim(base: usize, enr: *mut u32, bit: u32, ccr: u32) {
    write_volatile(enr, read_volatile(enr) | 1 << bit);
    w(base, 0x28, 0);
    w(base, 0x2C, 99);
    w(base, 0x34, ccr);
    w(base, 0x18, 0x68);
    w(base, 0x20, 1);
    if base == TIM1 {
        w(base, 0x44, 0x8000);
    }
    w(base, 0x14, 1);
    w(base, 0x00, 0x81);
    let mut i = 0u32;
    while i < 5000 {
        write_volatile(MARK_READ2, i);
        i += 1;
    }
}

#[cfg(any(path = "ardupilot", path = "gen-s03"))]
unsafe fn replay(seq: &[(usize, u8, u32)]) {
    for &(a, width, v) in seq {
        match width {
            32 => write_volatile(a as *mut u32, v),
            16 => write_volatile(a as *mut u16, v as u16),
            _ => write_volatile(a as *mut u8, v as u8),
        }
    }
}

