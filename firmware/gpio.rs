#[no_mangle]
pub unsafe extern "C" fn reset() -> ! {
    write_volatile(RCC_AHB4ENR, 0x7FF);
    #[cfg(path = "valid")]
    {
        afsel(GPIOA, 5, 5);
        mode(GPIOA, 5, 2);
    }
    #[cfg(path = "blank")]
    {
        afsel(GPIOA, 5, 6);
        mode(GPIOA, 5, 2);
    }
    #[cfg(path = "blankfirst")]
    {
        mode(GPIOA, 6, 2);
    }
    #[cfg(path = "twice")]
    {
        afsel(GPIOA, 5, 6);
        mode(GPIOA, 5, 2);
        mode(GPIOA, 6, 1);
    }
    #[cfg(path = "afterwards")]
    {
        afsel(GPIOA, 5, 5);
        mode(GPIOA, 5, 2);
        afsel(GPIOA, 5, 6);
    }
    #[cfg(path = "afrh")]
    {
        write_volatile((GPIOA + AFRH) as *mut u16, (r(GPIOA, AFRH) as u16) & !(0xF << 4));
        mode(GPIOA, 9, 2);
    }
    #[cfg(path = "package")]
    {
        mode(GPIOH, 2, 1);
    }
    #[cfg(path = "packageinput")]
    {
        let mut port = GPIOA;
        while port <= 0x5802_2800 {
            w(port, MODER, 0);
            port += 0x400;
        }
    }
    #[cfg(path = "pk8af")]
    {
        mode(GPIOK, 8, 2);
    }
    #[cfg(path = "pk8out")]
    {
        mode(GPIOK, 8, 1);
    }
    #[cfg(path = "pc2")]
    {
        mode(GPIOC, 2, 1);
    }
    #[cfg(path = "pupdr")]
    {
        w(GPIOA, PUPDR, (r(GPIOA, PUPDR) & !3) | 3);
    }
    #[cfg(path = "lckr")]
    {
        w(GPIOA, LCKR, (1 << 16) | 1);
    }
    #[cfg(path = "brr")]
    {
        w(GPIOA, 0x28, 1);
    }
    #[cfg(path = "read")]
    {
        write_volatile(MARK_READ, r(GPIOA, 0x2C));
    }
    #[cfg(path = "bsrr")]
    {
        w(GPIOA, ODR, 0);
        w(GPIOA, BSRR, (1 << 16) | 1);
        write_volatile(MARK_READ, r(GPIOA, ODR));
    }
    #[cfg(path = "bsrrhalf")]
    {
        write_volatile((GPIOA + BSRR) as *mut u16, 1);
        write_volatile(MARK_READ, r(GPIOA, ODR));
        write_volatile((GPIOA + BSRR + 2) as *mut u16, 1);
        write_volatile(MARK_READ, (read_volatile(MARK_READ) << 4) | r(GPIOA, ODR));
    }
    #[cfg(path = "otyper")]
    {
        w(GPIOA, OTYPER, 0x00C0);
        write_volatile(MARK_READ, r(GPIOA, OTYPER));
    }
    #[cfg(path = "analogled")]
    {
        w(GPIOB, BSRR, 1);
        write_volatile(MARK_READ, (r(GPIOB, ODR) & 0xFFFF) << 16 | (r(GPIOB, IDR) & 0xFFFF));
    }
    #[cfg(path = "analogout")]
    {
        w(GPIOB, BSRR, 1);
        mode(GPIOB, 0, 1);
        write_volatile(MARK_READ, r(GPIOB, IDR));
    }
    #[cfg(path = "odrfirst")]
    {
        w(GPIOB, ODR, 1);
        mode(GPIOB, 0, 1);
    }
    #[cfg(path = "moderfirst")]
    {
        mode(GPIOB, 0, 1);
        w(GPIOB, ODR, 1);
    }
    #[cfg(path = "analoghold")]
    {
        mode(GPIOB, 0, 1);
        w(GPIOB, BSRR, 1);
        mode(GPIOB, 0, 3);
        write_volatile(MARK_READ, r(GPIOB, IDR));
    }
    #[cfg(path = "afodr")]
    {
        afsel(GPIOA, 8, 1);
        mode(GPIOA, 8, 2);
        tim(TIM1, RCC_APB2ENR, 0, 0);
        w(GPIOA, ODR, 0x100);
        write_volatile(MARK_READ, (r(GPIOA, ODR) & 0xFFFF) << 16 | (r(GPIOA, IDR) & 0xFFFF));
    }
    #[cfg(path = "afenter")]
    {
        w(GPIOA, BSRR, 1 << 8);
        mode(GPIOA, 8, 1);
        tim(TIM1, RCC_APB2ENR, 0, 0);
        afsel(GPIOA, 8, 1);
        mode(GPIOA, 8, 2);
        write_volatile(MARK_READ, r(GPIOA, IDR));
    }
    #[cfg(path = "afenterhigh")]
    {
        mode(GPIOA, 8, 1);
        tim(TIM1, RCC_APB2ENR, 0, 200);
        afsel(GPIOA, 8, 1);
        mode(GPIOA, 8, 2);
        write_volatile(MARK_READ, r(GPIOA, IDR));
    }
    #[cfg(path = "afout")]
    {
        afsel(GPIOA, 8, 1);
        mode(GPIOA, 8, 2);
        tim(TIM1, RCC_APB2ENR, 0, 0);
        w(GPIOA, BSRR, 1 << 8);
        mode(GPIOA, 8, 1);
        let out = r(GPIOA, IDR) >> 8 & 1;
        mode(GPIOA, 8, 2);
        write_volatile(MARK_READ, out << 1 | (r(GPIOA, IDR) >> 8 & 1));
    }
    #[cfg(path = "afentern")]
    {
        mode(GPIOA, 7, 1);
        tim(TIM1, RCC_APB2ENR, 0, 0);
        afsel(GPIOA, 7, 1);
        mode(GPIOA, 7, 2);
        write_volatile(MARK_READ, r(GPIOA, IDR));
    }
    #[cfg(path = "afswitch")]
    {
        tim(0x4000_0000, RCC_APB1LENR, 0, 0);
        tim(0x4000_0C00, RCC_APB1LENR, 3, 200);
        afsel(GPIOA, 0, 1);
        mode(GPIOA, 0, 2);
        let before = r(GPIOA, IDR) & 1;
        afsel(GPIOA, 0, 2);
        write_volatile(MARK_READ, before << 1 | (r(GPIOA, IDR) & 1));
    }
    #[cfg(path = "afnosrc")]
    {
        mode(GPIOA, 5, 1);
        w(GPIOA, BSRR, 1 << 5);
        afsel(GPIOA, 5, 5);
        mode(GPIOA, 5, 2);
        w(GPIOA, BSRR, 1 << 21);
        write_volatile(MARK_READ, r(GPIOA, IDR));
        w(GPIOA, PUPDR, r(GPIOA, PUPDR) | 2 << 10);
    }
    #[cfg(path = "odrhalf")]
    {
        write_volatile((GPIOB + ODR) as *mut u16, 1);
        write_volatile(MARK_READ, r(GPIOB, ODR));
    }
    #[cfg(path = "inputidr")]
    {
        mode(GPIOD, 0, 1);
        w(GPIOD, BSRR, 1);
        mode(GPIOD, 0, 0);
        mode(GPIOD, 1, 0);
        mode(GPIOD, 2, 1);
        w(GPIOD, BSRR, 1 << 2);
        mode(GPIOD, 2, 0);
        w(GPIOD, PUPDR, (1 << 2) | (2 << 4) | (1 << 8));
        mode(GPIOD, 3, 1);
        w(GPIOD, BSRR, (1 << 3) | (1 << 4) | (1 << 6));
        mode(GPIOD, 5, 0);
        mode(GPIOD, 6, 0);
        write_volatile(MARK_READ, r(GPIOD, IDR) & 0xFF);
        write_volatile(MARK_READ2, r(GPIOD, ODR));
    }
    #[cfg(path = "ardupilot")]
    replay(&SEQ_AP);
    #[cfg(path = "gen-s03")]
    replay(&SEQ_S03);
    write_volatile(MARK_AFTER, 0xAF7E_0002);
    loop {}
}

#[panic_handler]
fn panic(_: &core::panic::PanicInfo) -> ! {
    loop {}
}
