//! Bare-metal probes for the GPIO guard (TVI-WO-1301). No dependencies; built with rustc alone, as spi1.rs and rcc.rs.
//! Variant chosen at build time with `--cfg path="..."`. Every path first enables the eleven ports' clocks
//! (RCC_AHB4ENR = 0x7FF, GPIOAEN..GPIOKEN, RM0433 Rev 9 §8.7.42 p461), as both firmwares do before any GPIO access
//! (TVI-WO-1301.rm0433.md §2), then makes its own accesses and writes the after-marker.
//!   path="valid"        - PA5 AFSEL = 5 (SPI1_SCK, DS12117 Table 9 p89), then MODER5 = 10: passes.
//!   path="blank"        - PA5 AFSEL = 6 (blank on p89), then MODER5 = 10: TVI-GPIO-AF, predicted-fault, at the MODER store.
//!   path="blankfirst"   - PA6 put in AF mode with its AFSEL at reset (AF0, blank on p89): TVI-GPIO-AF at the MODER store.
//!   path="afterwards"   - PA5 in AF mode on AF5, then AFSEL changed to 6: TVI-GPIO-AF at the AFRL store.
//!   path="twice"        - "blank", then MODER written again with PA5 still in AF mode: in recorded mode, one would-refuse.
//!   path="afrh"         - PA9 AFSEL (AFRH) = 0 with MODER9 = 10 (PA9 AF0: blank on p89), the AFRH store a half-word:
//!                         TVI-GPIO-AF at the MODER store (a sub-word AFRH write merged, then judged).
//!   path="package"      - PH2 (not bonded on LQFP144, Table 8 p68) set to output: TVI-GPIO-PACKAGE, predicted-fault.
//!   path="packageinput" - every port's MODER written as input (a whole-port init, PH2-PH15 included): passes.
//!   path="pk8af"        - PK8 (no such pin: Table 9 lists PK0-PK7, p100) in AF mode: TVI-GPIO-AF, predicted-fault.
//!   path="pk8out"       - PK8 set to output, on LQFP144: TVI-GPIO-PACKAGE, predicted-fault.
//!   path="pc2"          - PC2 set to output on LQFP144 (bonded only through PC2_C, footnote 4 p88): unmodeled.
//!   path="pupdr"        - PUPDR0 = 11 (reserved, p542): TVI-GPIO-FIELD, unmodeled.
//!   path="lckr"         - LCKR = LCKK | LCK0, the lock key sequence's first write: TVI-GPIO-FIELD, unmodeled (p545).
//!   path="brr"          - a write at 0x28 (no register on the H7; the stock port's RM0090 BRR): TVI-GPIO-FIELD.
//!   path="read"         - a read at 0x2C (no register): TVI-GPIO-READ, unmodeled.
//!   path="bsrr"         - ODR0 cleared, then BSRR = BS0 | BR0: BS has priority (p544), so ODR0 reads 1: passes.
//!   path="bsrrhalf"     - BSRR's halves written as 16-bit stores (ArduPilot's form): BS0, then BR0: passes.
//!   path="otyper"       - OTYPER = 0x00C0 (open-drain on pins 6, 7): kept and read back: passes.
//!   path="ardupilot", "gen-s03" - ArduPilot's first 886 GPIO writes (every pin state it ever enters; widths kept)
//!                         and sentinel-03's 88, as measured (TVI-WO-1301 §1.1): each passes, enforcing (WO §2).
//! TVI-WO-1301a, what drives a pin (RM0433 Rev 9 §11.3.9-11.3.13 p537-539). MARK_READ and MARK_READ2 keep what is read:
//!   path="analogled"   - BSRR = 1 on PB0, analog from reset: GreenLED stays dark (p539); MARK_READ = ODR_B << 16 | IDR_B
//!                        (ODR0 reads 1, as written, p537; IDR0 reads 0, analog, p539).
//!   path="analogout"   - the same, then MODER PB0 = output: GreenLED lights with the latched ODR; MARK_READ = IDR_B.
//!   path="odrfirst"    - ODR = 1 on port B, then PB0 output ("set ODR, then output"): GreenLED lit.
//!   path="moderfirst"  - PB0 output, then ODR = 1: GreenLED lit.
//!   path="analoghold"  - PB0 output with ODR0 = 1, then analog: nothing drives it, so it is low (p539); IDR0 reads 0.
//!   path="afodr"       - PA8 AF1 (TIM1_CH1, DS12117 Table 9 p89), TIM1 PWM held low (CCR1 = 0), then ODR = 0x100: the
//!                        pin follows TIM1, not ODR (p538); MARK_READ = ODR_A << 16 | IDR_A.
//!   path="afenter"     - PA8 output high, then AF1 with TIM1 low: the pin takes TIM1's level at the switch; MARK_READ = IDR_A.
//!   path="afenterhigh" - PA8 output low, TIM1 driving high (CCR1 > ARR), then AF1: the pin goes high at the switch.
//!   path="afout"       - PA8 AF1 with TIM1 low and ODR8 = 1, then output (high), then AF again (low):
//!                        MARK_READ = IDR8 after output << 1 | IDR8 after AF.
//!   path="afentern"    - PA7 output low, TIM1 CH1 low, then AF1 (TIM1_CH1N, p89): the pin takes the level Renode's
//!                        routing gives CH1N, CH1 inverted (stm32h7.repl invertedAFPins [7, 1, 3]; CCxNE is not gated there).
//!   path="odrhalf"     - a 16-bit store of 1 to port B's ODR, PB0 analog: latched (ODR0 reads 1), GreenLED dark.
//!   path="idle"        - nothing but the marker: a monitor-driven case runs it so that emulation can advance.
//!   path="inputidr"    - port D: PD0 output high, then input (floating: reads 0); PD1 input, then pulled up; PD2 output
//!                        high, input (held), then pulled down (PUPDR, p542: the pin follows each pull); PD3 output high;
//!                        PD4 analog with ODR4 = 1 and a pull-up written (no pull in analog, p539: IDR 0, the pin low);
//!                        PD5 input, declared up by the test's platform; PD6 input with ODR6 = 1 (floating: 0); PD7
//!                        analog, declared up (the pin high, IDR7 0, p539). MARK_READ = IDR_D, MARK_READ2 = ODR_D.
//!   path="afswitch"    - PA0 on AF1 (TIM2_CH1, p89) with TIM2 low, then AFSEL = 2 (TIM5_CH1) with TIM5 high, in AF mode:
//!                        the pin follows the newly selected AF. MARK_READ = IDR0 before << 1 | IDR0 after.
//!   path="afnosrc"     - PA5 output high, then AF5 (SPI1_SCK, p89; no Renode model drives a pin), then BSRR resets ODR5:
