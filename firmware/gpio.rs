//! Bare-metal probes for the GPIO guard (TVI-WO-1301). No dependencies; built with rustc alone, as spi1.rs and rcc.rs.
//! Variant chosen at build time with `--cfg path="..."`. Every path first enables the eleven ports' clocks
//! (RCC_AHB4ENR = 0x7FF, GPIOAEN..GPIOKEN, RM0433 Rev 9 §8.7.42 p461), as both firmwares do before any GPIO access
//! (TVI-WO-1301.rm0433.md §2), then makes its own accesses and writes the after-marker.
//!   path="valid"        - PA5 AFSEL = 5 (SPI1_SCK, DS12117 Table 9 p89), then MODER5 = 10: passes.
//!   path="blank"        - PA5 AFSEL = 6 (blank on p89), then MODER5 = 10: TVI-GPIO-AF, predicted-fault, at the MODER store.
//!   path="blankfirst"   - PA6 put in AF mode with its AFSEL at reset (AF0, blank on p89): TVI-GPIO-AF at the MODER store.
//!   path="afterwards"   - PA5 in AF mode on AF5, then AFSEL changed to 6: TVI-GPIO-AF at the AFRL store.
//!   path="twice"        - "blank", then MODER written again with PA5 still in AF mode: in recorded mode, one would-refuse.
//!   path="afrh"         - PA9 AFSEL (AFRH) = 0 with MODER9 = 10 (PA9 AF0: blank on p89), the AFRH store a half-word:
//!                         TVI-GPIO-AF at the MODER store (a sub-word AFRH write merged, then judged).
//!   path="package"      - PH2 (not bonded on LQFP144, Table 8 p68) set to output: TVI-GPIO-PACKAGE, predicted-fault.
//!   path="packageinput" - every port's MODER written as input (a whole-port init, PH2-PH15 included): passes.
//!   path="pc2"          - PC2 set to output on LQFP144 (bonded only through PC2_C, footnote 4 p88): unmodeled.
//!   path="pupdr"        - PUPDR0 = 11 (reserved, p542): TVI-GPIO-FIELD, unmodeled.
//!   path="lckr"         - LCKR = LCKK | LCK0, the lock key sequence's first write: TVI-GPIO-FIELD, unmodeled (p545).
//!   path="brr"          - a write at 0x28 (no register on the H7; the stock port's RM0090 BRR): TVI-GPIO-FIELD.
//!   path="read"         - a read at 0x2C (no register): TVI-GPIO-READ, unmodeled.
//!   path="bsrr"         - ODR0 cleared, then BSRR = BS0 | BR0: BS has priority (p544), so ODR0 reads 1: passes.
//!   path="bsrrhalf"     - BSRR's halves written as 16-bit stores (ArduPilot's form): BS0, then BR0: passes.
//!   path="otyper"       - OTYPER = 0x00C0 (open-drain on pins 6, 7): kept and read back: passes.
//!   path="ardupilot", "gen-s03" - ArduPilot's first 886 GPIO writes (every pin state it ever enters; widths kept)
//!                         and sentinel-03's 88, as measured (TVI-WO-1301 §1.1): each passes, enforcing (WO §2).
//! Bits: RM0433 Rev 9 §11.4 p541-546.
#![no_std]
#![no_main]
#![allow(dead_code)]

use core::ptr::{read_volatile, write_volatile};

const RCC_AHB4ENR: *mut u32 = 0x5802_44E0 as *mut u32;
const GPIOA: usize = 0x5802_0000;
const GPIOC: usize = 0x5802_0800;
const GPIOH: usize = 0x5802_1C00;
const MODER: usize = 0x00;
const OTYPER: usize = 0x04;
const PUPDR: usize = 0x0C;
const ODR: usize = 0x14;
const BSRR: usize = 0x18;
const LCKR: usize = 0x1C;
const AFRL: usize = 0x20;
const AFRH: usize = 0x24;
/// Marker in DTCM, read back by the test: the firmware got past its last guarded access.
const MARK_AFTER: *mut u32 = 0x2000_0104 as *mut u32;
/// Where a read's value is kept, so the test can see it.
const MARK_READ: *mut u32 = 0x2000_0108 as *mut u32;

unsafe fn w(port: usize, off: usize, v: u32) {
    write_volatile((port + off) as *mut u32, v);
}

unsafe fn r(port: usize, off: usize) -> u32 {
    read_volatile((port + off) as *const u32)
}

unsafe fn mode(port: usize, pin: u32, m: u32) {
    w(port, MODER, (r(port, MODER) & !(3 << (2 * pin))) | (m << (2 * pin)));
}

unsafe fn afsel(port: usize, pin: u32, af: u32) {
    let off = if pin < 8 { AFRL } else { AFRH };
    let sh = 4 * (pin & 7);
    w(port, off, (r(port, off) & !(0xF << sh)) | (af << sh));
}

#[cfg(any(path = "ardupilot", path = "gen-s03"))]
unsafe fn replay(seq: &[(usize, u8, u32)]) {
    for &(a, width, v) in seq {
        match width {
            32 => write_volatile(a as *mut u32, v),
            16 => write_volatile(a as *mut u16, v as u16),
            _ => write_volatile(a as *mut u8, v as u8),
        }
    }
}

