"""TVI-WO-1206 §1.3: put the readings (spike/1206/data/readings.tsv) into the guards' field tables, the rows' class and text only.

Usage: python3 -I spike/1206/apply.py spike/1206/data/readings.tsv   (from the repository root; idempotent)

- The five generated tables: each generator (tests/1300/allowlist.py, tests/1302, 1303, 1305, 1306 fields.py) gets its readings as one
  data block, READ_1206 = {(register, row name): (class, behaves as)}, between the marker lines below, and one line where a row
  is emitted that takes the reading's class and text in place of the classification's. The allowed set is never touched.
- The two hand-written tables (GuardedSTM32_GPIOPort.cs, GuardedSTM32H7_SPI.cs): the row's class and text, in place.
The generated tables are then regenerated by their generators (the regen cases' own commands) and spliced between the markers
those cases compare."""
import re, subprocess, sys

BEGIN, END = '# TVI-WO-1206 readings BEGIN (spike/1206/apply.py writes this block; spike/1206/readings.py derives it)\n', '# TVI-WO-1206 readings END\n'
GEN = {  # guard -> (generator, its data argument, hook anchor, hook line inserted before the anchor)
    'GuardedSTM32H7_RCC': ('tests/1300/allowlist.py', None,
                           "        out.append(f\"            R({cs(x['reg'])}",
                           "        k, b = READ_1206.get((x['reg'], csname(x)), (ledger_class(x), x['behaves']))  # TVI-WO-1206\n"),
    'GuardedSTM32_Timer': ('tests/1302/fields.py', 'tests/1302/data/rm0433-rev9-tim18-fields.tsv',
                           "    esc = lambda s: s.replace('\\\\', '\\\\\\\\').replace('\"', '\\\\\"')\n",
                           "    k, behaves = READ_1206.get((reg, name), (k, behaves))  # TVI-WO-1206\n"),
    'GuardedSTM32F7_USART': ('tests/1305/fields.py', 'tests/1305/data/rm0433-rev9-usart-fields.tsv',
                             "    print('            R(%s, %s, %s, %s, %s, %s, %s, %s, %s, %s),' % (cs(reg), off,",
                             "    c, behaves = READ_1206.get((reg, name), (c, behaves))  # TVI-WO-1206\n"),
    'GuardedSTM32DMA': ('tests/1303/fields.py', '',
                        '        print("            R(%s, %s, %s, %s, %d, %d, %s, %s, %s, %d)," % (q(reg), lit(off), q(sec), q(name),',
                        "        cls, behaves = READ_1206.get((reg, name), (cls, behaves))  # TVI-WO-1206\n"),
    'GuardedSTM32F7_I2C': ('tests/1306/fields.py', 'tests/1306/data/rm0433-rev9-i2c-fields.tsv',
                           "        print('            R(\"%s\", 0x%03X, \"%s\", \"%s\", %d, %d, %s, \"%s\", \"%s\", %d),' % (reg, int(off, 16), sec, name, a, b,",
                           "        c, behaves = READ_1206.get((reg, name), (c, behaves))  # TVI-WO-1206\n"),
}
HAND = {'GuardedSTM32_GPIOPort', 'GuardedSTM32H7_SPI'}
OPEN, CLOSE = '        private static readonly Row[] Fields =\n        {\n', '        };\n'

readings = [l.rstrip('\n').split('\t') for l in open(sys.argv[1]) if not l.startswith('#')]
items = {l.split('\t')[0]: l.split('\t')[1] for f in ('spike/1206/data/items.tsv', 'spike/1206/data/items2.tsv') for l in open(f) if not l.startswith('#')}
by_guard = {}
for field, state, _, cls, text in readings:
    if state == 'held': continue
    guard = items[field].split(':')[0].split('/')[-1][:-3]
    reg, name = field.split('.', 1)
    by_guard.setdefault(guard, {})[(reg, name)] = (cls, text)


def edit_generator(path, data, anchor, hook):
    s = open(path).read()
    block = BEGIN + 'READ_1206 = {\n' + ''.join('    %r: %r,\n' % (k, v) for k, v in sorted(data.items())) + '}\n' + END
    if BEGIN in s:
        s = s[:s.index(BEGIN)] + block + s[s.index(END) + len(END):]
    else:
        m = re.search(r'^import [^\n]*\n', s, re.M)
        s = s[:m.end()] + block + s[m.end():]
    if hook not in s:
        assert s.count(anchor) == 1, (path, anchor)
        s = s.replace(anchor, hook + anchor)
    if path.endswith('allowlist.py'):  # its emitter must use the reading's class and text
        a = "{cs(ledger_class(x))}, {cs(x['behaves'])}, {x['page']}),\\n\")"
        if a in s:
            s = s.replace(a, "{cs(k)}, {cs(b)}, {x['page']}),\\n\")")
    open(path, 'w').write(s)


for guard, (gen, arg, anchor, hook) in GEN.items():
    edit_generator(gen, by_guard.get(guard, {}), anchor, hook)
    model = 'model/%s.cs' % guard
    if arg is None:
        subprocess.run(['python3', '-I', gen, 'write'], check=True)
    else:
        rows = subprocess.run(['python3', '-I', gen] + ([arg] if arg else []), check=True, capture_output=True, text=True).stdout
        m = open(model).read()
        i = m.index(OPEN) + len(OPEN); j = m.index(CLOSE, i)
        open(model, 'w').write(m[:i] + rows.rstrip('\n') + '\n' + m[j:])
assert set(by_guard) <= set(GEN) | HAND, sorted(set(by_guard) - set(GEN) - HAND)
for guard in HAND:
    model = 'model/%s.cs' % guard
    m = open(model).read()
    for (reg, name), (cls, text) in by_guard.get(guard, {}).items():
        pat = re.compile(r'(R\("%s", [^,]+, "[^"]*", "%s", \d+, \d+, (?:new uint\[\] \{[^}]*\}|[^,]+), )("[^"]*(?:\\.[^"]*)*"|Inherited), ("(?:[^"\\]|\\.)*")(, \d+\))'
                         % (re.escape(reg), re.escape(name)))
        esc = lambda t: '"' + t.replace('\\', '\\\\').replace('"', '\\"') + '"'
        m, n = pat.subn(lambda x: x.group(1) + esc(cls) + ', ' + esc(text) + x.group(4), m)
        assert n == 1, (guard, reg, name, n)
    open(model, 'w').write(m)
print('applied: %s' % ', '.join('%s %d' % (g, len(v)) for g, v in sorted(by_guard.items())))
