#!/usr/bin/env python3
"""TVI-WO-1301 §1.1: write the SCRATCH PROTOTYPE GpioProto1301.cs (measurement only, not a model) from the committed
table. Usage: proto1301.py model/ds12117-rev10-table9.tsv > GpioProto1301.cs"""
import csv, sys
rows = list(csv.DictReader(open(sys.argv[1], encoding='utf-8'), delimiter='\t'))
pins = {}
for r in rows:
    pins.setdefault(r['pin'], [None] * 16)[int(r['af'])] = (r['cell'], r['page'])
order = sorted(pins, key=lambda p: (p[1], int(p[2:])))
cs = lambda s: '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
table = ',\n'.join('            new Cell[] { ' + ', '.join(f'C({cs(c)}, {pg})' for c, pg in pins[p]) + ' } /* ' + p + ' */' for p in order)
index = ', '.join(cs(p) for p in order)
# the allow-list's shape (rows as RCC's R(...)); this prototype only carries them, for the compile's cost
fields = []
for reg, off, page, per, w, kind in [('GPIOx_MODER', 0x00, 543, 16, 2, 'guard copy'), ('GPIOx_OTYPER', 0x04, 543, 16, 1, 'tag'),
        ('GPIOx_OSPEEDR', 0x08, 544, 16, 2, 'inherited'), ('GPIOx_PUPDR', 0x0C, 544, 16, 2, 'inherited'),
        ('GPIOx_IDR', 0x10, 545, 16, 1, 'read-only'), ('GPIOx_ODR', 0x14, 545, 16, 1, 'inherited'),
        ('GPIOx_BSRR', 0x18, 545, 32, 1, 'guard'), ('GPIOx_LCKR', 0x1C, 545, 17, 1, 'refused'),
        ('GPIOx_AFRL', 0x20, 546, 8, 4, 'guard copy'), ('GPIOx_AFRH', 0x24, 546, 8, 4, 'guard copy')]:
    for i in range(per):
        lsb = i * w
        fields.append(f'            R({cs(reg)}, 0x{off:03X}, "§11.4", {cs(reg.split("_")[1] + str(i))}, {lsb + w - 1}, {lsb}, Any, {cs(kind)}, "prototype", {page})')
print(f'''// TVI-WO-1301 §1.1 SCRATCH PROTOTYPE (measurement only, not a model), generated by tests/1301/proto1301.py.
// RUL-07's subclass form over the unsealed stock STM32_GPIOPort: it re-implements the three bus access interfaces and
// forwards every access to the stock port unchanged (transparent). It carries DS12117 Rev 10 Table 9 (2,688 cells) and an
// allow-list in the RCC guard's row shape, so the one-file compilation costs what the guard's would. It evaluates the
// alternate-function rule after each write (a pin in AF mode whose AFSEL names a blank cell), as a would-refuse in
// recorded mode, once per pin each time the condition arises. With trace: true it logs every access as `TVI1301-T`.
using System;
using System.Collections.Generic;
using System.Linq;
using Antmicro.Renode.Core;
using Antmicro.Renode.Logging;
using Antmicro.Renode.Peripherals.Bus;
using Antmicro.Renode.Peripherals.GPIOPort;

namespace Antmicro.Renode.Peripherals.Tviburi
{{
    public class GpioProto1301 : STM32_GPIOPort, IDoubleWordPeripheral, IWordPeripheral, IBytePeripheral, IDisposable
    {{
        public GpioProto1301(IMachine machine, uint modeResetValue = 0, uint outputSpeedResetValue = 0, uint pullUpPullDownResetValue = 0,
            uint numberOfAFs = 16, List<List<int>> invertedAFPins = null, string mode = "enforcing", bool trace = false)
            : base(machine, modeResetValue, outputSpeedResetValue, pullUpPullDownResetValue, numberOfAFs, invertedAFPins)
        {{
            this.machine = machine;
            this.trace = trace;
            records = new Records(machine, this, nameof(GpioProto1301), mode);
        }}

        public void Dispose()
        {{
            records.End();
        }}

        public new uint ReadDoubleWord(long offset)
        {{
            var v = base.ReadDoubleWord(offset);
            Trace("R", 32, offset, v);
            return v;
        }}

        public new void WriteDoubleWord(long offset, uint value)
        {{
            base.WriteDoubleWord(offset, value);
            Trace("W", 32, offset, value);
            Check(offset);
        }}

        public ushort ReadWord(long offset)
        {{
            var v = (ushort)(base.ReadDoubleWord(offset & ~3L) >> (int)(8 * (offset & 3)));
            Trace("R", 16, offset, v);
            return v;
        }}

        public void WriteWord(long offset, ushort value)
        {{
            var aligned = offset & ~3L;
            var shift = (int)(8 * (offset & 3));
            // BSRR is write-only (reads 0): a sub-word write to it is the half it names, not a merge (RM0433 Rev 9 p545)
            var merged = aligned == 0x18 ? (uint)value << shift : (base.ReadDoubleWord(aligned) & ~(0xFFFFu << shift)) | ((uint)value << shift);
            base.WriteDoubleWord(aligned, merged);
            Trace("W", 16, offset, value);
            Check(aligned);
        }}

        public byte ReadByte(long offset)
        {{
            var v = (byte)(base.ReadDoubleWord(offset & ~3L) >> (int)(8 * (offset & 3)));
            Trace("R", 8, offset, v);
            return v;
        }}

        public void WriteByte(long offset, byte value)
        {{
            var aligned = offset & ~3L;
            var shift = (int)(8 * (offset & 3));
            var merged = aligned == 0x18 ? (uint)value << shift : (base.ReadDoubleWord(aligned) & ~(0xFFu << shift)) | ((uint)value << shift);
            base.WriteDoubleWord(aligned, merged);
            Trace("W", 8, offset, value);
            Check(aligned);
        }}

        // The query: which signal pin P carries now, from MODER, AFSEL and the table (DS12117 Rev 10 Table 9).
        public string WhichSignal(int pin)
        {{
            var mode = (base.ReadDoubleWord(0x00) >> (2 * pin)) & 3;
            if(mode != 2)
            {{
                return mode == 0 ? "input" : mode == 1 ? "output" : "analog";
            }}
            var af = (int)((base.ReadDoubleWord(pin < 8 ? 0x20 : 0x24) >> (4 * (pin & 7))) & 0xF);
            var cell = Lookup(pin, af);
            return cell == null ? "unknown" : cell.Text == "-" ? "none (AF" + af + ", blank, p" + cell.Page + ")" : cell.Text + " (AF" + af + ", p" + cell.Page + ")";
        }}

        private void Check(long offset)
        {{
            if(offset != 0x00 && offset != 0x20 && offset != 0x24)
            {{
                return;
            }}
            var moder = base.ReadDoubleWord(0x00);
            for(var pin = 0; pin < 16; pin++)
            {{
                var af = (int)((base.ReadDoubleWord(pin < 8 ? 0x20 : 0x24) >> (4 * (pin & 7))) & 0xF);
                var cell = Lookup(pin, af);
                var bad = ((moder >> (2 * pin)) & 3) == 2 && cell != null && cell.Text == "-";
                if(bad && (faulted & (1 << pin)) == 0)
                {{
                    records.Refuse("TVI-GPIO-AF", "predicted-fault", offset == 0x00 ? "GPIOx_MODER" : pin < 8 ? "GPIOx_AFRL" : "GPIOx_AFRH",
                        "P" + Port + pin + " AF" + af, "pin P" + Port + pin + " in alternate-function mode (MODER = 10) selects AF" + af
                        + ", which has no function on that pin", "DS12117 Rev 10 Table 9 p" + cell.Page + "; RM0433 Rev 9 p543, p546",
                        "MODER=0x" + moder.ToString("X8"), offset, 0, 32);
                }}
                faulted = bad ? faulted | (1 << pin) : faulted & ~(1 << pin);
            }}
        }}

        private Cell Lookup(int pin, int af)
        {{
            var i = Array.IndexOf(Pins, "P" + Port + pin);
            return i < 0 ? null : Table[i][af];
        }}

        private char Port
        {{
            get
            {{
                if(port == '\\0')
                {{
                    var start = machine.SystemBus.GetRegistrationPoints(this).First().Range.StartAddress;
                    port = (char)('A' + (int)((start - 0x58020000UL) / 0x400UL));
                }}
                return port;
            }}
        }}

        private void Trace(string op, int width, long offset, uint value)
        {{
            if(!trace)
            {{
                return;
            }}
            var pc = machine.SystemBus.TryGetCurrentCPU(out var cpu) ? "0x" + cpu.PC.RawValue.ToString("X8") : "none";
            this.Log(LogLevel.Warning, "TVI1301-T {{0}} P{{1}} {{2}}{{3}} off=0x{{4:X2}} val=0x{{5:X}} pc={{6}} moder=0x{{7:X8}} afrl=0x{{8:X8}} afrh=0x{{9:X8}}",
                seq++, Port, op, width, offset, value, pc, base.ReadDoubleWord(0x00), base.ReadDoubleWord(0x20), base.ReadDoubleWord(0x24));
        }}

        private sealed class Cell
        {{
            public Cell(string text, int page) {{ Text = text; Page = page; }}
            public readonly string Text;
            public readonly int Page;
        }}

        private sealed class Row
        {{
            public Row(string reg, long off, string sec, string name, int msb, int lsb, uint[] allowed, string cls, string behaves, int page)
            {{ Reg = reg; Off = off; Sec = sec; Name = name; Msb = msb; Lsb = lsb; Allowed = allowed; Cls = cls; Behaves = behaves; Page = page; }}
            public readonly string Reg, Sec, Name, Cls, Behaves;
            public readonly long Off;
            public readonly int Msb, Lsb, Page;
            public readonly uint[] Allowed;
        }}

        private static Cell C(string text, int page) {{ return new Cell(text, page); }}
        private static Row R(string reg, long off, string sec, string name, int msb, int lsb, uint[] allowed, string cls, string behaves, int page)
        {{ return new Row(reg, off, sec, name, msb, lsb, allowed, cls, behaves, page); }}

        private static readonly uint[] Any = null;
        public static int FieldCount => Fields.Length;

        private static readonly string[] Pins = {{ {index} }};

        private static readonly Cell[][] Table =
        {{
{table}
        }};

        private static readonly Row[] Fields =
        {{
{(','+chr(10)).join(fields)}
        }};

        private readonly IMachine machine;
        private readonly Records records;
        private readonly bool trace;
        private char port;
        private int faulted;
        private long seq;
    }}
}}''')
