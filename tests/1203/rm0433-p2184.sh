#!/bin/bash
# tests/1203/rm0433-p2184.sh [HELD_TEXT] — TVI-WO-1203 (3): regenerate tests/1203/rm0433-rev9-p2184.txt from the held RM0433 Rev 9
# text (default ~/.cache/aet-held/rm0433-rev9.txt, sha256 8e02c0c01d35d22a…) and compare it, byte for byte, with the committed
# file: the §50.5.2 heading, the "Mode fault (MODF)" paragraph, and page 2184's footer, verbatim, by the held text's line
# numbers. Run where the held text is (Furnace); CI reads the committed excerpt (tests/spike.sh modf-page). Exit 0 on a match.
set -euo pipefail
held=${1:-$HOME/.cache/aet-held/rm0433-rev9.txt}
here=$(cd "$(dirname "$0")" && pwd)
want=8e02c0c01d35d22a69e41325a382170d03ad17ff3c36a756f5e1c77fb659cfb4
