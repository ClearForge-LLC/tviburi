{ printf '# RM0433 Rev 9, the held text (sha256 %s), lines 85634, 85741-85752 and 85777, verbatim:\n' "$want"
  printf '# the heading of the section the paragraph sits in (on p2181), the "Mode fault (MODF)" paragraph, and p2184'"'"'s footer.\n'
  printf '# Regenerated by tests/1203/rm0433-p2184.sh; read by tests/spike.sh modf-page (gate clause 4).\n'
  sed -n '85634p;85741,85752p;85777p' "$held"; } > "$here/rm0433-rev9-p2184.new"
if cmp -s "$here/rm0433-rev9-p2184.new" "$here/rm0433-rev9-p2184.txt"; then rm -f "$here/rm0433-rev9-p2184.new"; echo "rm0433-p2184: match"; else echo "rm0433-p2184: DIFFERS (see $here/rm0433-rev9-p2184.new)"; exit 1; fi
